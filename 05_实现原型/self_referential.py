# 界面问题检测
INTERFACE_QUERY_PATTERNS = [
    # 界面/布局/页面
    r"界面|页面|屏幕|布局|网页(上|里)|这个(网站|系统|页面)",
    # 按钮/控件
    r"按钮|控件|开关|选项卡|下拉|菜单|图标|tab",
    # 使用/操作
    r"怎么用|怎么操作|怎么(开始|进入)|使用方法|如何(使用|操作)|用法|操作指南",
    # 功能（界面层）
    r"(这个|这些|这里|界面)(有)?(什么|哪些).{0,4}(功能|按钮|东西|选项)",
    r"功能(介绍|说明|列表|清单)|都有什么功能",
    # 模式
    r"模式(切换|怎么|啥意思|区别)|怎么(切换|换)模式",
    # 特定操作
    r"(登录|注册|主题|上传|下载).{0,4}(按钮|在哪|怎么)",
    r"学科(下拉|选择|列表|都有)|学段(选择|都有)",
]
INTERFACE_COMPILED = [re.compile(p, re.IGNORECASE) for p in INTERFACE_QUERY_PATTERNS]


def is_interface_query(text: str) -> bool:
    """判断是否"界面/按钮/使用"类问题。"""
    t = (text or "").strip()
    if not t or len(t) > 80:
        return False
    return any(p.search(t) for p in INTERFACE_COMPILED)


def handle_interface_query(concept: str, learner=None) -> str:
    """按关键词分桶返回界面说明。

    命中多桶 → 拼接对应段落；否则返回完整指南。
    """
    t = (concept or "")
    buckets = []
    for kws, bucket in KEYWORD_BUCKETS:
        if any(kw in t for kw in kws) and bucket not in buckets:
            buckets.append(bucket)

    intro = (
        "好的，我来给你讲清楚这个界面：\n\n"
        "这是 **Émile 的教室**——左边是你的学习档案，中间是对话区，"
        "顶部和输入栏有各种功能。下面按你问的说明：\n\n"
    )

    if not buckets:
        # 完整指南
        body = "\n\n".join(INTERFACE_GUIDE.values())
    else:
        body = "\n\n".join(INTERFACE_GUIDE[b] for b in buckets)

    outro = (
        "\n\n如果还有哪个按钮不清楚，直接问我——比如「怎么上传资料」「历史会话怎么恢复」，"
        "我会告诉你。"
    )
    return intro + body + outro


