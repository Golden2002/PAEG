"""
PAEG 自我指涉模块（v0.19.27 ⭐ Self-Referential）

用户会问"这个界面上不同的按钮是做什么用的""怎么使用这个网站"——
agent 需要能正确回答。本模块把"PAEG 界面/功能/按钮"作为**结构化知识**，
用确定性模板回答（界面是确定性知识，LLM 自由生成易漏掉按钮或描述不准）。

方案（推荐方案 A：不走 LLM，直接按子主题返回模板段落）：
- is_interface_query(text)：检测是否"界面/按钮/使用"类问题
- handle_interface_query(concept)：按关键词分桶，返回对应说明段落
- 若命中多桶 → 拼接；否则返回完整指南
"""

