"""
intent_router.py — 文件操作意图路由（v0.21.5）
=============================================

职责
----
用户上传文件后，对用户消息做关键词级别的意图路由，决定走以下 4 种流程中的哪一种：

* ``FILE_QA``             — 找答案
* ``FILE_EXPLAIN``        — 讲解
* ``FILE_QUOTE``          — 摘录原文
* ``FILE_RESTRUCTURE``    — 重组结构

并提供两个辅助函数：

* ``is_file_operation(query)`` — 判断用户**是否在操作已上传的文件**
  （给 server 当“是否走文件操作流程”的总开关）；
* ``extract_filename(query)`` — 从用户消息中抽取被显式提到的文件名。

设计要点
--------
1. **关键词规则路由**：纯正则/字符串匹配，零依赖、可解释、易调试；
   后续可无缝替换为 LLM 分类器（接口兼容）。
2. **命中优先级**：``FILE_RESTRUCTURE`` > ``FILE_QUOTE`` > ``FILE_EXPLAIN`` > ``FILE_QA``；
   - 重构/原文/讲解的关键词非常独特，命中即可锁定；
   - 找答案的关键词最常见且易与其他意图共存（如“找答案并讲解”），优先级最低；
   - 命中多个同优先级意图或都不命中 → 默认 ``FILE_QA``（最常用）。
3. **文件名抽取**：依次尝试三种格式——
   - 中文书名号 ``《filename.ext》``；
   - 中英文双引号 / 单引号 ``"filename.ext"`` ``'filename.ext'``；
   - 位置模式（“按/根据/用 XXX 讲 / 讲解 / 重组 …”）。
4. **文件操作判定 (is_file_operation)**：触发词列表独立且比意图路由的关键词更宽，
   任何包含“我的资料/上传的文件/讲义/笔记/文件里”等触发词都视为文件操作。

依赖：仅标准库 ``re`` 与本包内的 ``intents.Intent``。
"""
