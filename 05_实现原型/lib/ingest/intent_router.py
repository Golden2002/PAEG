# ---------------------------------------------------------------------------
# 文件名抽取
# ---------------------------------------------------------------------------
# 三种候选正则（按优先级排列）：
#   1) 中文书名号《xxx.ext》
#   2) 中英文双/单引号 "xxx.ext" / 'xxx.ext'
#   3) 位置模式（“按/根据/用 xxx 讲 / 讲解 / 重组 / 整理 …”）
# ---------------------------------------------------------------------------
_FILENAME_PATTERNS: tuple = (
    # 1) 《filename.ext》 —— 支持中文/英文文件名 + 常见扩展名
    re.compile(r"《(?P<name>[^》]{1,80}?\.[a-zA-Z0-9]{1,5})》"),
    # 2) "filename.ext" / 'filename.ext'
    re.compile(r"""["'“”‘’](?P<name>[^"'“”‘’]{1,80}?\.[a-zA-Z0-9]{1,5})["'“”‘’]"""),
    # 3) 位置模式：按/根据/用/依据/依照 + 文件名 + (讲|讲解|解释|重组|整理|总结|展开|摘录|…)
    #    文件名段允许中文 / 英文 / 数字 / 下划线 / 点 / 空格 / 短横线，长度 1-60
    re.compile(
        r"(?:按|根据|依据|依照|用|基于)"
        r"(?P<name>[\u4e00-\u9fa5A-Za-z0-9_\-\. ]{1,60}?\.[a-zA-Z0-9]{1,5})"
        r"(?=\s*(?:讲|讲解|解释|说明|展开|总结|梳理|重组|整理|分析|摘录|摘抄|找|搜|查|说说|看看|学习))"
    ),
)

# 简单的扩展名白名单（避免误把“没有扩展名的句子片段”当文件名）
_VALID_EXTS: frozenset = frozenset({
    # 文档
    "pdf", "doc", "docx", "ppt", "pptx", "xls", "xlsx", "csv", "txt", "md", "rtf", "odt",
    # 代码 / 数据
    "py", "js", "ts", "java", "c", "cpp", "h", "hpp", "go", "rs", "sh", "json", "xml", "yaml", "yml", "html", "htm",
    # 图片 / 媒体
    "png", "jpg", "jpeg", "gif", "bmp", "webp", "svg", "mp3", "mp4", "wav", "mov", "avi",
    # 其他常见
    "log", "ini", "conf", "tex", "bib",
})


# ---------------------------------------------------------------------------
# 内部小工具
# ---------------------------------------------------------------------------
def _contains_any(text: str, keywords) -> bool:
    """子串匹配：text 中是否包含 keywords 任意一条。"""
    return any(kw in text for kw in keywords)


def _valid_filename(name: str) -> bool:
    """粗校验：扩展名是否在白名单 + 长度合理 + 不含明显非文件名字符。"""
    if not name or len(name) > 80 or len(name) < 2:
        return False
    if "." not in name:
        return False
    ext = name.rsplit(".", 1)[-1].lower()
    if ext not in _VALID_EXTS:
        return False
    # 不应包含明显的句子边界标点（避免误命中整句）
    if any(ch in name for ch in "。！？!?；;，,"):
        return False
    return True


