def route_intent(query: str) -> Intent:
    """对用户消息做关键词规则路由，返回 4 种文件操作意图之一。

    规则
    ----
    1. 若 ``query`` 为空或全空白 → 默认 ``FILE_QA``；
    2. 按 ``FILE_RESTRUCTURE`` → ``FILE_QUOTE`` → ``FILE_EXPLAIN`` → ``FILE_QA``
       的优先级顺序匹配；
    3. 命中第一个（最高优先级）的意图即返回；
    4. 若多个意图同时命中，按优先级取最高的；
    5. 若所有意图都不命中 → 默认 ``FILE_QA``（最常用）。

    参数
    ----
    query: 用户原始消息字符串。

    返回
    ----
    ``Intent`` 枚举值（FILE_QA / FILE_EXPLAIN / FILE_QUOTE / FILE_RESTRUCTURE）。
    """
    if not query or not query.strip():
        return Intent.FILE_QA

    # 按优先级从高到低扫描
    matched: list = []
    for intent in (
        Intent.FILE_RESTRUCTURE,
        Intent.FILE_QUOTE,
        Intent.FILE_EXPLAIN,
        Intent.FILE_QA,
    ):
        if _contains_any(query, _INTENT_KEYWORDS[intent]):
            matched.append(intent)

    if not matched:
        return Intent.FILE_QA

    # 多意图命中：取优先级最高的一个
    matched.sort(key=lambda i: _INTENT_PRIORITY[i], reverse=True)
    return matched[0]


def is_file_operation(query: str) -> bool:
    """判断用户消息是否在操作已上传的文件。

    用于 server 端做“是否走文件操作流程（检索 → 拼 prompt → 调 LLM）”的总开关。

    判定规则
    --------
    只要消息中包含下列任一触发词，即视为文件操作：

    * “我的资料 / 我的笔记 / 我的讲义 / 我的文件”；
    * “上传的文件 / 上传的讲义 / 上传的资料 / 上传的笔记 / 我上传的 / 刚才上传 / 刚发的 / 刚上传”；
    * “资料里 / 笔记里 / 讲义里 / 文件里 / 文档里”；
    * “根据讲义 / 按讲义 / 依据讲义 / 用讲义 / 根据资料 / 按资料 / 依据资料 / 用资料 / 根据笔记 / 按笔记 / 依据笔记 / 用笔记”；
    * “根据我 / 按我”；
    * “文件中的 / 文档中的”。

    参数
    ----
    query: 用户原始消息字符串。

    返回
    ----
    ``True`` 表示这是文件操作请求；``False`` 表示不是。
    """
    if not query or not query.strip():
        return False
    # 1) 触发词命中
    if _contains_any(query, _FILE_OPERATION_TRIGGERS):
        return True
    # 2) 包含显式文件名（《xxx.ext》 / "xxx.ext"）也算文件操作
    if extract_filename(query) is not None:
        return True
    return False


def extract_filename(query: str) -> Optional[str]:
    """从用户消息中抽取被显式提到的文件名。

    按下列顺序尝试：

    1. 中文书名号 ``《filename.ext》`` —— 最显式，优先；
    2. 中英文引号包裹 ``"filename.ext"`` / ``'filename.ext'``；
    3. 位置模式（“按/根据/用/依据/依照/基于 + 文件名 + 讲/讲解/解释/重组/整理/…”）。

    抽取后会做扩展名白名单 + 标点过滤，未通过校验返回 ``None``。

    参数
    ----
    query: 用户原始消息字符串。

    返回
    ----
    抽取到的文件名（不含路径、不含书名号/引号），未抽到返回 ``None``。

    示例
    ----
    >>> extract_filename("按《高等数学讲义.pdf》讲解导数")
    '高等数学讲义.pdf'
    >>> extract_filename('根据 "notes.md" 总结成大纲')
    'notes.md'
    >>> extract_filename("用 讲义.docx 讲解第一章")
    '讲义.docx'
    >>> extract_filename("讲讲导数") is None
    True
    """
    if not query or not query.strip():
        return None

    # 用列表显式列举要去掉的“书名号/引号”字符，避免在源码里写易出错的字面量
    _STRIP_CHARS = " \t\n\r\u300a\u300b\u201c\u201d\u2018\u2019\"'"

    for pat in _FILENAME_PATTERNS:
        m = pat.search(query)
        if m:
            name = m.group("name").strip().strip(_STRIP_CHARS)
            if _valid_filename(name):
                return name

    return None


