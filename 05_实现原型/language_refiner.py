            r"^(你|我)?(也)?(可以|应该|先|暂时)?(不用|不必|无需|不需要|别|不要)(用)?(着急|急着|急|催|赶)",
            r"^(先|暂时|现在)?(不必|不用|无需|不需要)(着急|急着|急|催|赶)",
            r"^(先|暂时|现在|此刻)?(不|别|不必|不要)(用)?(着急|急着|急|催|赶)(说|讲|回答|下结论|给|告诉|表态|解释)?",
