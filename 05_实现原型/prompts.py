def _load_persona(persona_id: str = "weil") -> str:
    """从 paeg_personas/{persona_id}.yml 加载 persona 正文（缺失回退空串）。"""
    try:
        _p = _os_persona.path.join(_PERSONA_DIR, f"{persona_id}.yml")
        if not _os_persona.path.isfile(_p):
            return ""
        _txt = open(_p, encoding="utf-8").read()
        _lines = _txt.splitlines()
        _body_start = None
        for _i, _l in enumerate(_lines):
            if _l.strip() == "body: |":
                _body_start = _i + 1
                break
        if _body_start is None:
            return ""
        _body = _lines[_body_start:]
        _indents = [len(_l) - len(_l.lstrip()) for _l in _body if _l.strip()]
        _min_ind = min(_indents) if _indents else 0
        return "\n".join(_l[_min_ind:] if _l.strip() else "" for _l in _body).strip()
    except Exception:
        return ""


