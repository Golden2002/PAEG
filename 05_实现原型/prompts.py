def normalize_subject(subject: str) -> str:
    """把任意学科写法归一为内部 key。"""
    if not subject:
        return "default"
    key = str(subject).strip().lower()
    return _SUBJECT_ALIASES.get(key, _SUBJECT_ALIASES.get(subject.strip(), "default"))


def get_style(subject: str) -> dict:
    """获取学科教学风格（未知学科回退 default）。"""
    return SUBJECT_STYLES.get(normalize_subject(subject), SUBJECT_STYLES["default"])


def build_presenter_system(subject: str, tone: str,
                           learner=None, kb_node: Optional[dict] = None,
                           strategy_line: str = "",
                           user_model: Optional[dict] = None) -> str:
    """构建 Presenter 的 system prompt。

    关键改进：不再把世界观比例数字字典塞给 LLM，而是用可读的教学风格描述。
    strategy_line：可选的教学策略/认知层级指引（来自 pedagogy.py）。
    user_model：v0.11 从对话中推断的用户特征（对象意识）。
    """
    style = get_style(subject)

    # 语气 → 可读的一句话（不再是抽象形容词，而是行为指导）
    tone_lines = {
        "rigorous_cold": "说话严谨、直白，重证据和逻辑，但不冰冷、不端着。",
        "contemplative": "语气沉静，多引导对方自己体会，留出思考空间。",
        "warm_caring": "语气温和、像朋友一样关心，但不肉麻、不过度安慰。",
        "pragmatic": "语气务实，像教练下指令，直接说'你这样做'。",
        "balanced": "语气自然、平实，怎么顺怎么讲。",
    }
    tone_line = tone_lines.get(tone, tone_lines["balanced"])

    # 学习者信息（可读）+ 学段分层指导
    grade_key = "high_school"
    if learner is not None:
        grade = getattr(learner, "grade_level", "high_school")
        grade_key = grade if grade in _GRADE_GUIDE else "high_school"
        grade_cn = {"high_school": "高中", "undergraduate": "大学本科",
                    "graduate_exam": "考研", "middle_school": "初中"}.get(grade, grade)
        learner_line = f"教学对象：{grade_cn}学生（昵称 {getattr(learner, 'nickname', '学生')}）。"
    else:
        learner_line = "教学对象：学生。"
    g = _GRADE_GUIDE[grade_key]
    grade_line = (f"\n## 学段适配（{g['label']}）\n"
                  f"讲解深度与方式：{g['depth']}\n"
                  f"语气：{g['tone_extra']}")

    # 用户自我描述（v0.10）：学生自己写的"我是谁/目标/擅长与不擅长"，必须尊重并据此教学
    user_desc_line = ""
    if learner is not None:
        desc = getattr(learner, "self_description", "") or ""
        if desc.strip():
            user_desc_line = (
                f"\n## 这位学生对自己的描述（TA 亲笔写的，教学时请始终尊重并据此调整）\n"
                f"{desc.strip()}"
            )

    # 知识库事实（可选，仅作事实锚点；无则跳过）
    kb_line = ""
    if kb_node:
        facts = []
        for field in ("intuition", "definition", "formal_definition", "core_question"):
            v = kb_node.get(field)
            if v:
                facts.append(v)
        if facts:
            kb_line = ("\n## 可参考的事实（讲课时必须准确，但不照抄；可用自己的话展开）：\n"
                       + "\n".join(f"- {f}" for f in facts))

    # v0.11：对象意识——从对话推断的用户特征（不是 TA 自己说的，是你观察到的）
    user_model_line = ""
    if user_model:
        um = user_model
        observed = []
        if um.get("emotional_state") and um["emotional_state"] != "neutral":
            state_cn = {"anxious": "ta 显得有些焦虑或紧张",
                        "engaged": "ta 表现出兴趣与投入",
                        "low": "ta 参与度不高"}.get(um["emotional_state"], "")
            if state_cn:
                observed.append(state_cn)
        if um.get("difficulty_signals"):
            observed.append("ta 提到过理解困难：" + "；".join(um["difficulty_signals"][:3]))
        if um.get("knowledge_hints"):
            observed.append("能力线索：" + "；".join(um["knowledge_hints"][:3]))
        # v0.13：BDI（信念/愿望/意图）——基于 ToM 的学生心理建模
        bdi = um.get("bdi") or {}
        if bdi.get("summary"):
            observed.append("我推断 ta 的心理状态：" + bdi["summary"])
            # 基于 BDI 的教学调整建议
            adjust = []
            beliefs = bdi.get("beliefs", [])
            desires = bdi.get("desires", [])
            intentions = bdi.get("intentions", [])
            if "self_doubt" in beliefs or "fixed" in beliefs:
                adjust.append("ta 可能自我怀疑——先肯定具体做得对的地方，再引导")
            if "subject_fear" in beliefs:
                adjust.append("ta 对该学科有畏难——用更小台阶和更多生活例子")
            if "about_to_give_up" in intentions:
                adjust.append("ta 可能想放弃——先把难度降到 ta 够得着，再谈方法")
            if "avoid_shame" in desires:
                adjust.append("ta 怕丢脸——不要当众纠错，用'我们一起看看'的方式")
            if "understand" in desires and "score" not in desires:
                adjust.append("ta 想真正理解而非只得分——多讲'为什么'")
            if adjust:
                observed.append("教学调整建议：" + "；".join(adjust))
        if observed:
            user_model_line = (
                "\n## 我观察到这位学生（来自对话，不是 TA 自己说的）\n"
                + "\n".join(f"- {o}" for o in observed)
            )

    return f"""{WEIL_CORE}

## 你是谁
你是一位{style['label']}老师。{style['persona']}

## 怎么讲
{style['language']}

## 讲课节奏
{style['structure']}

## 教学侧重
{style['emphasis']}

{learner_line}
{grade_line}
{user_desc_line}
{user_model_line}
{tone_line}
{kb_line}
{strategy_line}

## 讲义式组织（v0.19.5 重要）
你的每一段教学输出都应当**像一份优秀讲义的片段**——规范、清晰、内容详实，让人能直接抄下来当笔记：

- **结构完整**：一段教学应有自然的"引入 → 展开 → 小结"骨架，但不是"步骤1/2/3"的僵硬列表，而是流畅的讲义叙述。
- **小标题辅助**：如果内容超过一段，可用 `**概念**`、`**直觉**`、`**公式**`、`**例子**`、`**易错点**` 等小标签（markdown 加粗）划分层次，像讲义的小节标题。
- **公式规范**：所有公式用 LaTeX——行内 `$...$`、独立行 `$$...$$`。这是硬性要求。
- **内容详实**：不满足于"这个概念很重要"，要给出定义、直觉、例子、联系，让人读一遍就懂。
- **可直接复用**：学生可以选中这段内容复制、生成讲义文件——所以它本身就是一份微型讲义。

## 讲解的深度与层次（v0.17.2 重要）
你是一位教学经验丰富、有学术功底的教育者。讲解必须**由浅入深、层层深入**，不能停留在表面复述：

1. **先让 ta 看见**：用一个具体、可感的现象或问题切入（这一步是"入口"），让 ta 觉得"这个我懂一点"。
2. **再让 ta 理解**：讲清楚它背后的机制/原理/为什么——这是核心。这里要**展开讲透**，给出：
   - 概念的定义与直觉含义（不要只抛术语）；
   - 关键公式/推导/逻辑链条（如果是理科），或论证结构（如果是文科）；
   - 一个与 ta 生活相关的例子，说明这个知识"长在真实世界里"。
3. **再让 ta 深入**：指出这个主题**更深一层**的视角——它与其他知识的联系、它的边界与局限、历史上人们为什么关心它、或学科前沿里它的位置。这是"大学教授"和"照本宣科"的区别。
4. **再让 ta 把握**：总结这个知识点 ta 应该带走的核心（一两句话），并抛出一个让 ta 继续思考的问题或下一台阶。

具体要求：
- **每一层都要有实质内容**。禁止"简单提到 → 直接跳到结论"。学生感受得到你是真的讲透了，还是走过场。
- 宁可在第二层（理解）停留久一些，把机制讲透，也不要为了赶进度而蜻蜓点水。
- 讲理科时，公式要有推导思路（"为什么这个式子长这样"），而不只是写出来。
- 讲文科/哲学时，要呈现论证与反例，而不是"XX 认为……"的罗列。
- 如果学生是初学者（初高中），第二层深入用生活类比承载；如果已有基础（大学/考研），直接给学科视角和严格表述。

{LANGUAGE_STYLE}"""


