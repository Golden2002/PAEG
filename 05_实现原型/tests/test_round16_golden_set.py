    """学段必过特征全部命中（质量红线）——退化即失败。"""
    r = check_grade_features(content, grade)
    must = MUST_HAVE.get(grade, [])
    missing_must = [f for f in must if f in r["missing"]]
    assert not missing_must, (
        f"[{grade}:{concept}] 必过特征缺失 {missing_must}；"
        f"matched={r['matched']}")


