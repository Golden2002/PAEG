# 每学段"必过特征"（质量红线：缺失即不合格）
MUST_HAVE = {
    "middle_school": ["生活化", "可视化", "复述引导"],   # 初中 3/3
    "high_school": ["定义公式", "例题", "误区"],          # 高中 3/3
    "undergraduate": ["严格定义", "学科视野"],            # 大学 2 核心（文理通用）
    "graduate_exam": ["考点定位", "题型套路", "易错得分"],  # 考研 3/4（真题示范文科可选）
}


@pytest.mark.parametrize("grade,subject,concept,content", GOLDEN)
def test_golden_grade_features(grade, subject, concept, content):
    """学段必过特征全部命中（质量红线）——退化即失败。"""
    r = check_grade_features(content, grade)
    must = MUST_HAVE.get(grade, [])
    missing_must = [f for f in must if f in r["missing"]]
    assert not missing_must, (
        f"[{grade}:{concept}] 必过特征缺失 {missing_must}；"
        f"matched={r['matched']}")


